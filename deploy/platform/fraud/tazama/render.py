#!/usr/bin/env python3
"""Generates tazama.yaml and kustomization.yaml (ADR-023). One entry per Tazama service; each gets the database
passwords for the stores its env file names (from the tazama-db secret). Run after adding a service or rule:
    python3 deploy/platform/fraud/tazama/render.py [--check]"""
import pathlib, re, sys

HERE = pathlib.Path(__file__).parent
SERVICES = [  # deployment name, image, env file, HTTP port (None: no HTTP), memory limit
    ("tms", "tms-service", "tms-service", 3000, "320Mi"),
    ("event-director", "event-director", "event-director", None, "256Mi"),
    ("rule-901", "rule-901", "rule-901", None, "256Mi"),
    ("rule-902", "rule-902", "rule-902", None, "256Mi"),
    ("rule-d01", "rule-d01", "rule-d01", None, "256Mi"),  # DIFME: ONNX fraud model (services/fraud-rules/rule-d01)
    ("rule-d02", "rule-d02", "rule-d02", None, "256Mi"),  # DIFME: amount anomaly, PDF §7.4 L1 (services/fraud-rules/rule-d02)
    ("typology-processor", "typology-processor", "typology-processor", None, "256Mi"),
    ("event-adjudicator", "event-adjudicator", "event-adjudicator", None, "256Mi"),
    ("admin-service", "admin-service", "admin-service", 3100, "320Mi"),  # evaluation reports for the payment hub
]

HEADER = """# GENERATED by render.py, do not edit. Tazama real-time fraud and AML monitoring (owner 2026-11-22, ADR-023) on
# DIFME's stack: Kafka (Strimzi) in place of NATS, the shared Postgres (databases tazama_*), the shared Valkey,
# OpenTelemetry to Alloy. Pipeline: TMS (ISO 20022 in) -> event director -> rule processors (901, 902, DIFME's D01) ->
# typology processor -> event adjudicator. Topics are created by the services from the network map. Images from
# deploy/images/tazama. Verified end to end: ci/tazama-e2e.sh.
apiVersion: v1
kind: ServiceAccount
metadata: { name: tazama }
automountServiceAccountToken: false
---
# Schema and configuration, idempotent (schema.sh): tables once, rules/typologies/network map into an empty store.
apiVersion: batch/v1
kind: Job
metadata: { name: tazama-schema, annotations: { argocd.argoproj.io/hook: Sync, argocd.argoproj.io/hook-delete-policy: BeforeHookCreation } }
spec:
  backoffLimit: 20
  template:
    metadata: { labels: { app: tazama-schema, difme/team: fraud } }
    spec:
      restartPolicy: OnFailure
      serviceAccountName: tazama
      securityContext: { runAsNonRoot: true, runAsUser: 70, seccompProfile: { type: RuntimeDefault } }
      containers:
        - name: schema
          image: postgres:17-alpine
          command: [sh, /sql/schema.sh, /sql]
          env:
            - { name: PGHOST, value: postgres-docdb.database-tier.svc }
            - { name: PGUSER, value: tazama }
            - { name: PGPASSWORD, valueFrom: { secretKeyRef: { name: tazama-db, key: password } } }
          volumeMounts: [{ name: sql, mountPath: /sql }]
          securityContext: { allowPrivilegeEscalation: false, readOnlyRootFilesystem: true, capabilities: { drop: [ALL] } }
          resources: { requests: { cpu: 10m, memory: 32Mi }, limits: { memory: 128Mi } }
      volumes: [{ name: sql, configMap: { name: tazama-sql } }]"""


def deployment(name, image, envf, port, mem):
    hosts = re.findall(r"^([A-Z_]+)_DATABASE_HOST=", (HERE / "env" / f"{envf}.env").read_text(), re.M)
    pw = "".join(f"\n            - {{ name: {h}_DATABASE_PASSWORD, valueFrom: {{ secretKeyRef: {{ name: tazama-db, key: password }} }} }}" for h in hosts)
    probe = (f"\n          ports: [{{ name: http, containerPort: {port} }}]"
             f"\n          readinessProbe: {{ httpGet: {{ path: /health, port: {port} }}, periodSeconds: 10 }}") if port else ""
    return f"""apiVersion: apps/v1
kind: Deployment
metadata: {{ name: tazama-{name}, labels: {{ app: tazama-{name} }} }}
spec:
  replicas: 1
  selector: {{ matchLabels: {{ app: tazama-{name} }} }}
  template:
    metadata: {{ labels: {{ app: tazama-{name}, difme/team: fraud, business.metric: fraud-monitoring }} }}
    spec:
      serviceAccountName: tazama
      securityContext: {{ runAsNonRoot: true, runAsUser: 1000, runAsGroup: 1000, seccompProfile: {{ type: RuntimeDefault }} }}
      containers:
        - name: {name}
          image: ghcr.io/pratikmohanty1994-ui/difme-tazama-{image}:0.1.0
          envFrom: [{{ configMapRef: {{ name: tazama-{envf} }} }}]
          env:
            - {{ name: APM_SERVICE_NAME, value: tazama-{name} }}{pw}{probe}
          securityContext: {{ allowPrivilegeEscalation: false, readOnlyRootFilesystem: true, capabilities: {{ drop: [ALL] }} }}
          resources: {{ requests: {{ cpu: 20m, memory: 96Mi }}, limits: {{ memory: {mem} }} }}"""


SERVICE = """apiVersion: v1
kind: Service
metadata: { name: tazama-tms }
spec:
  selector: { app: tazama-tms }
  ports: [{ name: http, port: 3000, targetPort: http }]
---
apiVersion: v1
kind: Service
metadata: { name: tazama-admin-service }
spec:
  selector: { app: tazama-admin-service }
  ports: [{ name: http, port: 3100, targetPort: http }]"""

docs = [HEADER] + [deployment(*s) for s in SERVICES] + [SERVICE]
outputs = {
    "tazama.yaml": "\n---\n".join(docs) + "\n",
    "kustomization.yaml": "# GENERATED by render.py. Tazama (ADR-023): env files are upstream defaults (tazama-stack v4.0.0)\n"
    "# pointed at DIFME's components.\nnamespace: fraud\nresources: [tazama.yaml]\n"
    "generatorOptions: { disableNameSuffixHash: true }\nconfigMapGenerator:\n"
    + "".join(f"  - name: tazama-{e}\n    envs: [env/{e}.env]\n" for e in sorted({s[2] for s in SERVICES}))
    + "  - name: tazama-sql\n    files:\n"
    + "".join(f"      - {f}\n" for f in [
        "../../../../vendor/tazama/stack-postgres/base/00-CREATE.sql",
        "../../../../vendor/tazama/stack-postgres/base/01-tcs-init.sql",
        "../../../../vendor/tazama/stack-postgres/base/02-trs-init.sql",
        "../../../../vendor/tazama/stack-postgres/config/00-public-base.sql",
        "difme-network-map.sql", "schema.sh"]),
}
stale = [n for n, text in outputs.items() if (HERE / n).read_text() != text] if (HERE / "tazama.yaml").exists() else list(outputs)
if "--check" in sys.argv:
    if stale: sys.exit(f"stale: {', '.join(stale)} (run render.py)")
    print("tazama manifests current")
else:
    for n, text in outputs.items(): (HERE / n).write_text(text)
    print("written:", ", ".join(outputs))
