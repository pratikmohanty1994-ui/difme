#!/usr/bin/env python3
"""OpenBao configuration for clusters whose OpenBao already exists (F2).

OpenBao's self-init `initialize` blocks (deploy/platform/security/openbao/values.yaml) run only when OpenBao starts
for the first time. This turns those blocks into a JSON list of API requests (requests.json), which the `openbao-config`
Job re-applies on every sync, idempotently, so a new mount, policy or role added to values.yaml reaches existing
clusters too. values.yaml stays the single source. `--check` fails when requests.json is stale (verify workflow).
"""
import json, pathlib, re, sys

HERE = pathlib.Path(__file__).parent
VALUES = HERE.parent / "openbao" / "values.yaml"
TOKEN = re.compile(r'\s*(?:(#[^\n]*)|("(?:[^"\\]|\\.)*")|([A-Za-z_][A-Za-z0-9_.-]*)|([{}\[\]=,]))')

def tokens(text):
    pos = 0
    while pos < len(text):
        m = TOKEN.match(text, pos)
        if not m or m.end() == pos:
            if text[pos:].strip() == "":
                return
            raise SystemExit(f"cannot parse near: {text[pos:pos+40]!r}")
        pos = m.end()
        if m.group(1):
            continue
        if m.group(2):
            yield ("str", json.loads(m.group(2)))
        elif m.group(3):
            yield ("id", m.group(3))
        else:
            yield ("p", m.group(4))

class P:
    def __init__(self, text):
        self.t = list(tokens(text)); self.i = 0
    def peek(self): return self.t[self.i] if self.i < len(self.t) else (None, None)
    def take(self, kind=None, val=None):
        k, v = self.peek()
        if (kind and k != kind) or (val and v != val):
            raise SystemExit(f"expected {kind} {val}, got {k} {v}")
        self.i += 1; return v
    def value(self):
        k, v = self.peek()
        if v == "{": return self.obj()
        if v == "[":
            self.take("p", "["); out = []
            while self.peek()[1] != "]":
                out.append(self.value())
                if self.peek()[1] == ",": self.take("p", ",")
            self.take("p", "]"); return out
        self.i += 1
        if k == "id": return {"true": True, "false": False}.get(v, v)
        return v
    def obj(self):
        self.take("p", "{"); out = {}
        while self.peek()[1] != "}":
            key = self.take()
            if self.peek()[1] == "=":
                self.take("p", "="); out[key] = self.value()
            else:  # block: name "label" { ... }
                label = self.take("str"); out.setdefault(key, {})[label] = self.obj()
            if self.peek()[1] == ",": self.take("p", ",")
        self.take("p", "}"); return out

def requests():
    text = VALUES.read_text()
    out = []
    for m in re.finditer(r'initialize "([^"]+)" \{', text):
        depth, j = 0, m.end() - 1
        for j in range(m.end() - 1, len(text)):
            depth += {"{": 1, "}": -1}.get(text[j], 0)
            if depth == 0: break
        block = P(text[m.end() - 1:j + 1]).obj()
        for name, r in block.get("request", {}).items():
            out.append({"block": m.group(1), "name": name, "operation": r.get("operation", "update"), "path": r["path"], "data": r.get("data", {})})
    return out

def script(reqs):
    """apply.sh: one idempotent call per request (sh + curl only, as in curlimages/curl)."""
    q = lambda s: "'" + s.replace("'", "'\\''") + "'"
    lines = ["#!/bin/sh", "# generated by render.py from openbao/values.yaml: do not edit", "set -u", "fail=0"]
    for r in reqs:
        body = json.dumps(r["data"], separators=(",", ":"), sort_keys=True)
        if r["path"].endswith("/root/generate/internal"):  # never rotate an existing CA
            mount = r["path"].split("/")[0]
            lines.append(f'if bao GET {mount}/cert/ca | grep -q "BEGIN CERTIFICATE"; then echo "= {r["path"]} (CA exists)"; else apply {q(r["path"])} {q(body)}; fi')
        else:
            lines.append(f"apply {q(r['path'])} {q(body)}")
    lines.append('[ "$fail" = 0 ] && echo "openbao configuration applied" || { echo "openbao configuration: $fail failed"; exit 1; }')
    return "\n".join(lines) + "\n"

if __name__ == "__main__":
    reqs = requests()
    files = {"requests.json": json.dumps(reqs, indent=1, sort_keys=True) + "\n", "apply.sh": script(reqs)}
    if "--check" in sys.argv:
        stale = [n for n, c in files.items() if not (HERE / n).exists() or (HERE / n).read_text() != c]
        if stale:
            sys.exit(f"openbao-config {stale} stale: run python3 deploy/platform/security/openbao-config/render.py")
        print("openbao requests current"); sys.exit(0)
    for n, c in files.items():
        (HERE / n).write_text(c)
    print(f"written: requests.json, apply.sh ({len(reqs)} requests)")
